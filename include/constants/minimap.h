#ifndef MINIMAP_CONSTANTS_H
#define MINIMAP_CONSTANTS_H

#define MINIMAP_TILE_BACKGROUND 0xA0

enum MinimapTileType {
    MINIMAP_TILE_TYPE_UNEXPLORED, // Gray
    MINIMAP_TILE_TYPE_NORMAL, // Pink
    MINIMAP_TILE_TYPE_HIDDEN, // Green

    MINIMAP_TILE_TYPE_COUNT
};

#define MINIMAP_TILE_NORMAL_FLAG (MINIMAP_TILE_TYPE_NORMAL << 12)
#define MINIMAP_TILE_HIDDEN_FLAG (MINIMAP_TILE_TYPE_HIDDEN << 12)

enum MinimapUpdateFlag {
    MINIMAP_UPDATE_FLAG_NONE,
    MINIMAP_UPDATE_FLAG_UPPER_LINE,
    MINIMAP_UPDATE_FLAG_MIDDLE_LINE,
    MINIMAP_UPDATE_FLAG_LOWER_LINE,

    MINIMAP_UPDATE_FLAG_COUNT
};

#endif /* MINIMAP_CONSTANTS_H */
